#!/usr/bin/env python3
"""Convert a SAM3 .npz checkpoint into a packed .wts file for fast runtime loading.

This script is OFFLINE-ONLY (Mac App Store constraint). The app/runtime should only load
prebuilt artifacts like .wts and must not invoke Python.

Format (little-endian):
- magic: 8 bytes: b"SAM3WTS1"
- numEntries: u32
Repeat entries:
- keyLen: u32
- key: utf-8 bytes
- dtype: u8   (1=float16, 2=float32, 3=int32, 4=int64, 5=uint8, 255=raw)
- rank: u8
- shape: u32 * rank
- byteLen: u32
- payload bytes

By default, float32 arrays are converted to float16 for performance.
"""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

import numpy as np

MAGIC = b"SAM3WTS1"  # 8 bytes

DTYPE_TO_CODE = {
    np.dtype(np.float16): 1,
    np.dtype(np.float32): 2,
    np.dtype(np.int32): 3,
    np.dtype(np.int64): 4,
    np.dtype(np.uint8): 5,
}


def _u32(x: int) -> bytes:
    return struct.pack("<I", int(x))



def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--npz", required=True, type=Path, help="Input .npz")
    ap.add_argument("--out", required=True, type=Path, help="Output .wts")
    ap.add_argument("--no-f16", action="store_true", help="Do not convert float32->float16 globally.")
    ap.add_argument("--inject", action="append", help="Inject file as key: KEY=PATH")
    ap.add_argument("--rename", action="append", help="Rename prefix: OLD=NEW")
    ap.add_argument("--force-f32", action="append", help="Keep specific keys as float32 (prefix match)")
    args = ap.parse_args()

    npz_path: Path = args.npz
    out_path: Path = args.out

    # Load base NPZ
    data = np.load(npz_path, allow_pickle=False)
    
    # Collect all items (key -> array)
    all_items = {}
    for key in data.files:
        all_items[key] = data[key]
        
    # Inject extra files
    if args.inject:
        for item in args.inject:
            ikey, ipath = item.split("=", 1)
            p = Path(ipath)
            if not p.exists():
                print(f"Warning: Injected file not found: {ipath}")
                continue
            # Read binary, assume float32 if .bin
            # If generated by numpy, we can load it?
            # gaussian_matrix.bin is raw bytes (float32).
            # We need to construct numpy array.
            # Assume flat float32 for raw files, unless we know shape?
            # For gaussian_matrix we know it's [2, 128].
            # But general injection is tricky regarding shape.
            # If suffix is .npy, load with numpy.
            if p.suffix == '.bin':
                # Assume raw float32. Shape is unknown but WTS needs shape.
                # For gaussian_matrix specifically: [2, 128]
                raw = np.fromfile(p, dtype=np.float32)
                if "gaussian" in ikey:
                    raw = raw.reshape(2, 128)
                all_items[ikey] = raw
            elif p.suffix == '.npy':
                all_items[ikey] = np.load(p)
            else:
                print(f"Warning: Unknown format for injected file {ipath}, skipping")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Prepare list for writing (handling updates/renames)
    final_keys = sorted(list(all_items.keys()))
    
    # Force F32 set
    force_f32_prefixes = args.force_f32 or []

    with out_path.open("wb") as f:
        f.write(MAGIC)
        f.write(_u32(len(final_keys)))

        for key in final_keys:
            arr = all_items[key]
            
            # Rename logic
            final_key = key
            if args.rename:
                for rule in args.rename:
                    old, new = rule.split("=", 1)
                    if final_key.startswith(old):
                        final_key = final_key.replace(old, new, 1)
                        break # Only one rename per key
            
            # Determine dtype conversion
            should_be_f16 = (not args.no_f16) and (arr.dtype == np.float32)
            
            # Check exemption
            for prefix in force_f32_prefixes:
                if final_key.startswith(prefix) or key.startswith(prefix):
                    should_be_f16 = False
                    break
            
            if should_be_f16:
                arr = arr.astype(np.float16, copy=False)
                
            arr = np.ascontiguousarray(arr)

            key_b = final_key.encode("utf-8")
            f.write(_u32(len(key_b)))
            f.write(key_b)

            code = DTYPE_TO_CODE.get(arr.dtype, 255)
            f.write(struct.pack("<B", int(code)))

            shape = tuple(int(x) for x in arr.shape)
            rank = len(shape)
            if rank > 255:
                raise RuntimeError(f"Rank too large for key={key!r}: {rank}")
            f.write(struct.pack("<B", rank))
            for dim in shape:
                f.write(_u32(dim))

            payload = arr.tobytes(order="C")
            f.write(_u32(len(payload)))
            f.write(payload)

    print(f"Wrote {len(final_keys)} tensors to: {out_path}")


if __name__ == "__main__":
    main()
