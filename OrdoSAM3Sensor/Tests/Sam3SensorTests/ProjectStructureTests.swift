
import XCTest
import Foundation
@testable import Sam3Sensor

final class ProjectStructureTests: XCTestCase {
    
    func testProjectRootCleanliness() throws {
        // Find project root relative to this test file
        // Tests/Sam3SensorTests/ProjectStructureTests.swift -> ../../
        let thisFile = URL(fileURLWithPath: #file)
        let rootURL = thisFile.deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        
        // Allowed files/folders in root - STRICT LIST
        let allowedItems: Set<String> = [
            "Package.swift",
            "README.md",
            ".gitignore",
            "docs",
            "sprints",
            "Sources",
            "Tests",
            "scripts",
            ".git",
            ".build",
            ".swiftpm",
            "Package.resolved", // Generated by SPM
            ".DS_Store",
            ".agent" // Helper for our work
        ]
        
        let fm = FileManager.default
        let items = try fm.contentsOfDirectory(atPath: rootURL.path)
        
        var violations: [String] = []
        
        for item in items {
            if !allowedItems.contains(item) {
                violations.append(item)
            }
        }
        
        XCTAssertTrue(violations.isEmpty, "Project root contains unauthorized files: \(violations). adhering to strict organization standards.")
    }
    
    func testSourcesOrganization() throws {
        let thisFile = URL(fileURLWithPath: #file)
        let sourcesURL = thisFile.deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent().appendingPathComponent("Sources")
        
        // Allowed modules in Sources
        let allowedModules: Set<String> = [
            "Sam3Sensor",
            "OrdoCli",
            ".DS_Store"
        ]
        
        let fm = FileManager.default
        if !fm.fileExists(atPath: sourcesURL.path) { return }
        
        let items = try fm.contentsOfDirectory(atPath: sourcesURL.path)
        for item in items {
             XCTAssertTrue(allowedModules.contains(item), "Sources/ contains unauthorized module: \(item)")
        }
    }
}
